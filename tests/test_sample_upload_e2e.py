def test_e2e_sample_upload():
    """Full end-to-end test simulating browser behavior."""
    
    # Use TESTING=True to enable X-Hopao-Role header
    app = create_app({"TESTING": True})
    client = app.test_client()
    
    # Headers to simulate logged-in operator
    headers = {"X-Hopao-Role": "operator"}
    
    print("=" * 60)
    print("E2E Test: Sample Upload Flow")
    print("=" * 60)
    
    # Step 1: Check /sample/new is accessible
    print("\n[Step 1] GET /sample/new ...")
    resp = client.get('/sample/new', headers=headers)
    print(f"  Status: {resp.status_code}")
    assert resp.status_code == 200, f"Expected 200, got {resp.status_code}"
    print("  ✅ Form page accessible")
    
    # Step 2: Upload temp file
    print("\n[Step 2] POST /sample/upload-temp ...")
    test_image = create_test_image_bytes()
    print(f"  Test image size: {len(test_image)} bytes")
    
    data = {
        'file': (io.BytesIO(test_image), 'test_upload.jpg', 'image/jpeg')
    }
    
    resp = client.post('/sample/upload-temp', 
                       data=data,
                       headers=headers,
                       content_type='multipart/form-data')
    
    print(f"  Status: {resp.status_code}")
    body = resp.get_data(as_text=True)
    print(f"  Body: {body}")
    
    if resp.status_code != 200:
        print(f"  ❌ FAILED: Upload returned {resp.status_code}")
        print(f"  This is likely the bug! Check body for error details.")
        return False
    
    import json
    result = json.loads(body)
    
    assert "temp_id" in result, "Missing temp_id in response"
    assert "preview_url" in result, "Missing preview_url in response"
    
    temp_id = result["temp_id"]
    preview_url = result["preview_url"]
    print(f"  ✅ Upload success. temp_id={temp_id[:8]}...")
    print(f"  preview_url: {preview_url}")
    
    # Step 3: Verify preview URL is accessible
    print(f"\n[Step 3] GET {preview_url} ...")
    resp = client.get(preview_url, headers=headers)
    print(f"  Status: {resp.status_code}")
    print(f"  Content-Type: {resp.content_type}")
    print(f"  Content-Length: {len(resp.data)} bytes")
    
    if resp.status_code != 200:
        print(f"  ❌ FAILED: Preview URL not accessible!")
        return False
    
    if not resp.content_type.startswith('image/'):
        print(f"  ⚠️ Warning: Content-Type is not image/*")
    
    print("  ✅ Preview URL accessible")
    
    # Step 4: Create sample with temp_id
    print("\n[Step 4] POST /sample/new (with temp_id) ...")
    form_data = {
        'name': 'E2E Test Sample',
        'title': 'Test Title',
        'sales_code': 'TEST-001',
        'version': 'V1',
        'fabric_no': '8888',
        'date_received': '2026-01-28',
        'printing_environment': 'Test Env',
        'printing_file_name': 'test.tif',
        'temp_id': temp_id,
        'remark': 'Created by E2E test'
    }
    
    resp = client.post('/sample/new', data=form_data, headers=headers)
    print(f"  Status: {resp.status_code}")
    
    if resp.status_code == 302:
        location = resp.headers.get('Location', '')
        print(f"  Redirect to: {location}")
        if '/sample/' in location:
            print("  ✅ Sample created successfully!")
        else:
            print(f"  ⚠️ Unexpected redirect: {location}")
    else:
        print(f"  Body: {resp.get_data(as_text=True)[:500]}")
        print("  ❌ FAILED: Expected 302 redirect")
        return False
    
    print("\n" + "=" * 60)
    print("🎉 ALL E2E TESTS PASSED!")
    print("=" * 60)
    return True


